CREATE TABLE staff_recovery_codes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_account_id integer NOT NULL REFERENCES staff_accounts(id) ON DELETE CASCADE,
  code_digest bytea NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  consumed_at timestamptz,
  CONSTRAINT staff_recovery_code_digest_length
    CHECK (octet_length(code_digest) = 32)
);

CREATE INDEX staff_recovery_codes_available
  ON staff_recovery_codes (staff_account_id, id)
  WHERE consumed_at IS NULL;

CREATE TABLE staff_auth_challenges (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_account_id integer NOT NULL REFERENCES staff_accounts(id) ON DELETE CASCADE,
  token_digest bytea NOT NULL UNIQUE,
  purpose varchar NOT NULL,
  failed_attempts smallint NOT NULL DEFAULT 0
    CHECK (failed_attempts BETWEEN 0 AND 5),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  CONSTRAINT staff_auth_challenges_digest_length
    CHECK (octet_length(token_digest) = 32),
  CONSTRAINT staff_auth_challenges_purpose_valid
    CHECK (purpose IN ('MFA_SIGN_IN', 'MFA_ENROLLMENT')),
  CONSTRAINT staff_auth_challenges_expiry_after_creation
    CHECK (expires_at > created_at)
);

CREATE INDEX staff_auth_challenges_active
  ON staff_auth_challenges (staff_account_id, expires_at)
  WHERE consumed_at IS NULL;

