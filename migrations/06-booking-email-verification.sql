CREATE TABLE booking_verification_challenges (
  booking_id integer PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
  code_digest bytea NOT NULL CHECK (octet_length(code_digest) = 32),
  expires_at timestamptz NOT NULL,
  failed_attempts smallint NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
  consumed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT booking_verification_challenges_expiry_after_update
    CHECK (expires_at > updated_at)
);

CREATE TABLE booking_verification_send_attempts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX booking_verification_send_attempts_recent
  ON booking_verification_send_attempts (booking_id, created_at DESC);

CREATE TABLE booking_tokens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  token_digest bytea NOT NULL UNIQUE CHECK (octet_length(token_digest) = 32),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  CONSTRAINT booking_tokens_expiry_after_creation CHECK (expires_at > created_at)
);

CREATE INDEX booking_tokens_booking_expiry
  ON booking_tokens (booking_id, expires_at)
  WHERE revoked_at IS NULL;

COMMENT ON TABLE booking_verification_send_attempts IS
  'Accepted code-send attempts used to enforce per-booking cooldown and rolling-hour limits; old rows are pruned on the next request.';
COMMENT ON COLUMN booking_verification_challenges.code_digest IS
  'HMAC-SHA-256 of the one-time email code; the plaintext code is never persisted.';
COMMENT ON COLUMN booking_tokens.token_digest IS
  'SHA-256 digest of the opaque booking bearer token; the raw token is returned once and never persisted.';
