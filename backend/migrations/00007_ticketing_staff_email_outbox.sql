CREATE TYPE "StaffRole" AS ENUM (
  'MANAGER',
  'SCANNER'
);

CREATE TYPE "StaffAccountStatus" AS ENUM (
  'INVITED',
  'ACTIVE',
  'DISABLED'
);

CREATE TYPE "EmailOutboxKind" AS ENUM (
  'BOOKING_TICKETS',
  'STAFF_INVITATION'
);

CREATE TYPE "EmailOutboxStatus" AS ENUM (
  'QUEUED',
  'SENDING',
  'SENT',
  'FAILED'
);

CREATE TABLE staff_accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar NOT NULL,
  display_name varchar NOT NULL,
  role "StaffRole" NOT NULL,
  status "StaffAccountStatus" NOT NULL,
  password_hash text,
  is_bootstrap_owner boolean NOT NULL DEFAULT false,
  created_by_staff_account_id integer REFERENCES staff_accounts(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT staff_accounts_email_normalized
    CHECK (email <> '' AND email = lower(btrim(email))),
  CONSTRAINT staff_accounts_display_name_not_empty
    CHECK (display_name <> '' AND display_name = btrim(display_name)),
  CONSTRAINT staff_invited_account_has_no_password
    CHECK (status <> 'INVITED' OR password_hash IS NULL),
  CONSTRAINT staff_active_account_requires_password
    CHECK (status <> 'ACTIVE' OR password_hash IS NOT NULL),
  CONSTRAINT staff_bootstrap_owner_is_manager
    CHECK (NOT is_bootstrap_owner OR role = 'MANAGER')
);

CREATE UNIQUE INDEX staff_accounts_one_bootstrap_owner
  ON staff_accounts (is_bootstrap_owner)
  WHERE is_bootstrap_owner;

CREATE TABLE staff_invitations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_account_id integer NOT NULL REFERENCES staff_accounts(id),
  token_digest bytea NOT NULL UNIQUE,
  token_ciphertext bytea,
  token_key_version smallint,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  revoked_at timestamptz,
  created_by_staff_account_id integer NOT NULL REFERENCES staff_accounts(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT staff_invitations_token_digest_length
    CHECK (octet_length(token_digest) = 32),
  CONSTRAINT staff_invitation_ciphertext_key_version_pair
    CHECK ((token_ciphertext IS NULL) = (token_key_version IS NULL)),
  CONSTRAINT staff_invitations_key_version_positive
    CHECK (token_key_version IS NULL OR token_key_version > 0),
  CONSTRAINT staff_invitations_expiry_after_creation
    CHECK (expires_at > created_at),
  CONSTRAINT staff_invitations_not_consumed_and_revoked
    CHECK (NOT (consumed_at IS NOT NULL AND revoked_at IS NOT NULL))
);

CREATE UNIQUE INDEX staff_invitations_one_active_per_account
  ON staff_invitations (staff_account_id)
  WHERE consumed_at IS NULL AND revoked_at IS NULL;

CREATE TABLE staff_sessions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_account_id integer NOT NULL REFERENCES staff_accounts(id),
  token_digest bytea NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  last_activity_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  CONSTRAINT staff_sessions_token_digest_length
    CHECK (octet_length(token_digest) = 32),
  CONSTRAINT staff_sessions_expiry_after_creation
    CHECK (expires_at > created_at),
  CONSTRAINT staff_sessions_last_activity_after_creation
    CHECK (last_activity_at >= created_at)
);

CREATE INDEX staff_sessions_active_by_account
  ON staff_sessions (staff_account_id, expires_at)
  WHERE revoked_at IS NULL;

CREATE TABLE tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL,
  seat_id integer NOT NULL,
  credential_digest bytea NOT NULL UNIQUE,
  credential_ciphertext bytea NOT NULL,
  credential_key_version smallint NOT NULL,
  redeemed_at timestamptz,
  redeemed_by_staff_account_id integer REFERENCES staff_accounts(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT tickets_booking_seat_unique UNIQUE (booking_id, seat_id),
  CONSTRAINT tickets_booking_seat_fkey
    FOREIGN KEY (booking_id, seat_id)
    REFERENCES bookings_seats (booking_id, seat_id),
  CONSTRAINT tickets_credential_digest_length
    CHECK (octet_length(credential_digest) = 32),
  CONSTRAINT tickets_credential_key_version_positive
    CHECK (credential_key_version > 0),
  CONSTRAINT tickets_redemption_audit_pair
    CHECK ((redeemed_at IS NULL) = (redeemed_by_staff_account_id IS NULL))
);

CREATE INDEX tickets_redeemed_by_staff
  ON tickets (redeemed_by_staff_account_id, redeemed_at)
  WHERE redeemed_by_staff_account_id IS NOT NULL;

CREATE TABLE email_outbox (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key varchar NOT NULL UNIQUE,
  kind "EmailOutboxKind" NOT NULL,
  recipient_email varchar NOT NULL,
  booking_id integer REFERENCES bookings(id),
  staff_invitation_id integer REFERENCES staff_invitations(id),
  status "EmailOutboxStatus" NOT NULL DEFAULT 'QUEUED',
  attempt_count integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  lease_expires_at timestamptz,
  last_error_code varchar,
  sent_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT email_outbox_attempt_count_nonnegative
    CHECK (attempt_count >= 0),
  CONSTRAINT email_outbox_sending_requires_lease
    CHECK ((status = 'SENDING') = (lease_expires_at IS NOT NULL)),
  CONSTRAINT email_outbox_sent_requires_timestamp
    CHECK ((status = 'SENT') = (sent_at IS NOT NULL)),
  CONSTRAINT email_outbox_kind_requires_matching_reference
    CHECK (
      (kind = 'BOOKING_TICKETS' AND booking_id IS NOT NULL AND staff_invitation_id IS NULL)
      OR
      (kind = 'STAFF_INVITATION' AND booking_id IS NULL AND staff_invitation_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX email_outbox_one_ticket_email_per_booking
  ON email_outbox (booking_id)
  WHERE kind = 'BOOKING_TICKETS';

CREATE UNIQUE INDEX email_outbox_one_invitation_email_per_invitation
  ON email_outbox (staff_invitation_id)
  WHERE kind = 'STAFF_INVITATION';

CREATE INDEX email_outbox_due_work
  ON email_outbox (next_attempt_at, id)
  WHERE status = 'QUEUED';

CREATE INDEX email_outbox_expired_leases
  ON email_outbox (lease_expires_at, id)
  WHERE status = 'SENDING';

COMMENT ON TABLE tickets IS
  'One admission ticket per booking seat. QR credentials are random bearer secrets; store a digest for lookup and authenticated-encryption ciphertext for re-rendering. The encryption key is kept outside PostgreSQL.';
COMMENT ON COLUMN tickets.redeemed_at IS
  'First successful staff redemption time; later scans must not overwrite this value.';
COMMENT ON TABLE staff_invitations IS
  'Single-use staff password-setup invitations. Clear token_ciphertext and token_key_version after successful email delivery or consumption, retaining the digest for validation.';
COMMENT ON INDEX staff_invitations_one_active_per_account IS
  'Expired invitations remain indexed until revoked; revoke the expired invitation before creating its replacement.';
COMMENT ON COLUMN staff_sessions.expires_at IS
  'Absolute session expiry; the application enforces the eight-hour maximum and fifteen-minute inactivity timeout.';
COMMENT ON TABLE email_outbox IS
  'Durable at-least-once email delivery queue. Provider timeouts after acceptance may produce duplicate emails, but must not duplicate tickets or booking side effects.';
